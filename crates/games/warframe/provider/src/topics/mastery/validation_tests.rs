//! Instruction windows from Warframe.x64.exe, fingerprint 6a85c6b0-02cef000.
//! Captured independently of the fact/validation code; no live account data.
use super::*;
use crate::topics::progression_tests::Image;

fn observed_image(base: u64) -> Image {
    let mut image = Image::new(base);
    image.extend(base, WINDOWS);
    image
}

#[test]
fn observed_layout_validates_at_unrelated_bases_and_rejects_changed_evidence()
-> Result<(), Box<dyn std::error::Error>> {
    for base in [0x1_4000_0000, 0x2_8000_0000] {
        let mut image = observed_image(base);
        validate_mastery_layout(&mut image, base, crate::target::BUILD.image_size)?;
        let mut reader = TargetReader::new(
            &mut image,
            base,
            crate::target::BUILD.image_size,
            READ_LIMITS,
        )?;
        crate::profile_inventory::validate_layout(&mut reader)?;
        crate::profile_inventory::validate_commit_fields(&mut reader)?;
        // Log reference/name, vector, XP codec, pool relation, rank codec and writer.
        for rva in [
            0x011f_b15f,
            0x0242_3170,
            0x011f_b188,
            0x011f_b1c8,
            0x002f_9009,
            0x011f_b2a9,
            0x01c1_d04e,
            0x0135_4be2,
            0x0135_4c22,
            0x00bc_bd72,
        ] {
            let mut image = observed_image(base);
            *image
                .bytes
                .get_mut(&(base + rva))
                .ok_or("missing instruction")? ^= 1;
            assert!(matches!(
                validate_mastery_layout(&mut image, base, crate::target::BUILD.image_size),
                Err(ReadError::LayoutMismatch { .. })
            ));
        }
        for &(rva, _) in &WINDOWS[6..] {
            let mut image = observed_image(base);
            *image
                .bytes
                .get_mut(&(base + u64::from(rva)))
                .ok_or("missing instruction")? ^= 1;
            let mut reader = TargetReader::new(
                &mut image,
                base,
                crate::target::BUILD.image_size,
                READ_LIMITS,
            )?;
            assert!(
                matches!(
                    crate::profile_inventory::validate_layout(&mut reader),
                    Err(ReadError::LayoutMismatch { .. })
                ) || matches!(
                    crate::profile_inventory::validate_commit_fields(&mut reader),
                    Err(ReadError::LayoutMismatch { .. })
                )
            );
        }
        image.bytes.remove(&(base + 0x011f_b15f));
        assert!(matches!(
            validate_mastery_layout(&mut image, base, crate::target::BUILD.image_size),
            Err(ReadError::Memory(_))
        ));
    }
    Ok(())
}

